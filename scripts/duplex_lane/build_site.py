#!/usr/bin/env python3
"""Retired legacy-lane publisher safety check.

Historical downloads are quarantined and must not be re-published from this
lane. The canonical site is generated by scripts/build_site.py.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main() -> int:
    published = [p for suffix in ("*.tif", "*.tiff", "*.zip")
                 for p in (ROOT / "docs").rglob(suffix)]
    if published:
        for path in published:
            print(f"BLOCKED: remove historical raster from Pages tree: {path.relative_to(ROOT)}")
        return 1
    print("BLOCKED release state confirmed: no historical submission raster is published from this lane.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
